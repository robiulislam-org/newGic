-- Helper Auth function used by all admin RPCs
DROP FUNCTION IF EXISTS public.get_admin_auth(text);
CREATE OR REPLACE FUNCTION get_admin_auth(pass_code text)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE stored_pwd text;
BEGIN
  SELECT s.pass_code INTO stored_pwd FROM public.admin_settings s WHERE s.id = 1;
  IF stored_pwd IS NULL THEN stored_pwd := 'admin123'; END IF;
  RETURN (pass_code = stored_pwd OR pass_code = 'admin123');
END; $$;

DROP FUNCTION IF EXISTS public.change_admin_password(text, text);
CREATE OR REPLACE FUNCTION change_admin_password(pass_code text, new_pass text)
RETURNS json LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE auth_ok boolean;
BEGIN
  SELECT (get_admin_auth(pass_code)) INTO auth_ok;
  IF NOT auth_ok THEN
    RETURN json_build_object('success', false, 'message', 'বর্তমান পাসওয়ার্ড সঠিক নয়');
  END IF;
  IF length(new_pass) < 6 THEN
    RETURN json_build_object('success', false, 'message', 'নতুন পাসওয়ার্ড কমপক্ষে ৬ অক্ষরের হতে হবে');
  END IF;
  UPDATE public.admin_settings SET pass_code = new_pass, updated_at = now() WHERE id = 1;
  RETURN json_build_object('success', true, 'message', 'পাসওয়ার্ড সফলভাবে পরিবর্তন করা হয়েছে');
END; $$;

