CREATE OR REPLACE FUNCTION get_teacher_bookings(pass_code text)
RETURNS json LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE auth_ok boolean; result json;
BEGIN
  SELECT (get_admin_auth(pass_code)) INTO auth_ok;
  IF NOT auth_ok THEN RETURN '[]'::json; END IF;
  SELECT json_agg(
    json_build_object(
      'id', b.id, 'teacher_id', b.teacher_id, 'teacher_name', COALESCE(b.teacher_name, t.name, '—'),
      'student_name', b.student_name, 'student_phone', b.student_phone,
      'student_msg', b.student_msg, 'slot_day', b.slot_day, 'slot_time', b.slot_time,
      'contact_type', b.contact_type, 'status', b.status, 'admin_notes', b.admin_notes,
      'created_at', b.created_at
    ) ORDER BY b.created_at DESC
  ) INTO result
  FROM public.teacher_bookings b
  LEFT JOIN public.teachers t ON t.id = b.teacher_id;
  RETURN COALESCE(result, '[]'::json);
END; $$;

