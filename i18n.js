let currentLang = localStorage.getItem("gic_lang") || "bn";

function t(key) {
  if (translations[currentLang] && translations[currentLang][key]) {
    return translations[currentLang][key];
  }
  return translations.bn[key] || key;
}

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem("gic_lang", lang);

  document.documentElement.lang = lang;
  document.documentElement.dir = (lang === "ar" ? "rtl" : "ltr");

  // Translate all elements with data-i18n
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang][key]) {
      el.innerText = translations[lang][key];
    }
  });

  // Translate placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  // Highlight active selector option
  document.querySelectorAll(".lang-btn").forEach(btn => {
    if (btn.dataset.lang === lang) {
      btn.style.background = "var(--gold)";
      btn.style.color = "#000";
      btn.style.fontWeight = "bold";
    } else {
      btn.style.background = "rgba(255,255,255,0.1)";
      btn.style.color = "#fff";
      btn.style.fontWeight = "normal";
    }
  });

  // Dispatch custom event for dynamic JS components
  window.dispatchEvent(new CustomEvent("gic_lang_change", { detail: { lang } }));
}

window.t = t;
window.setLanguage = setLanguage;
window.currentLang = currentLang;

// Initialize on DOM load
document.addEventListener("DOMContentLoaded", () => {
  setLanguage(currentLang);
});
