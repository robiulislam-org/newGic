-- ─────────────────────────────────────────────
-- TABLE 2: teacher_bookings
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.teacher_bookings (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id      bigint REFERENCES public.teachers(id) ON DELETE CASCADE,
  day_of_week     text NOT NULL CHECK (day_of_week IN ('sat','sun','mon','tue','wed')),
  slot_start      text NOT NULL,
  student_name    text DEFAULT '',
  student_phone   text DEFAULT '',
  message         text DEFAULT '',
  status          text DEFAULT 'pending' CHECK (status IN ('pending','confirmed','cancelled')),
  created_at      timestamptz DEFAULT now()
);

ALTER TABLE public.teacher_bookings ENABLE ROW LEVEL SECURITY;
CREATE POLICY "bookings_public_insert" ON public.teacher_bookings FOR INSERT WITH CHECK (true);
CREATE POLICY "bookings_no_public_read" ON public.teacher_bookings FOR SELECT USING (false);

CREATE INDEX IF NOT EXISTS idx_bookings_teacher ON public.teacher_bookings(teacher_id, status);

-- ─────────────────────────────────────────────
-- TABLE 3: teacher_reviews
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.teacher_reviews (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id     bigint REFERENCES public.teachers(id) ON DELETE CASCADE,
  reviewer_name  text DEFAULT 'এক অভিভাবক',
  rating         integer DEFAULT 5 CHECK (rating BETWEEN 1 AND 5),
  message        text NOT NULL,
  is_approved    boolean DEFAULT false,
  created_at     timestamptz DEFAULT now()
);

ALTER TABLE public.teacher_reviews ENABLE ROW LEVEL SECURITY;
CREATE POLICY "t_reviews_public_insert" ON public.teacher_reviews FOR INSERT WITH CHECK (true);
CREATE POLICY "t_reviews_public_read" ON public.teacher_reviews FOR SELECT USING (true);

CREATE INDEX IF NOT EXISTS idx_t_reviews_teacher ON public.teacher_reviews(teacher_id, is_approved);


