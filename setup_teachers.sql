-- 9. SUBMIT TEACHER REVIEW (PUBLIC)
CREATE OR REPLACE FUNCTION submit_teacher_review(
  p_teacher_id bigint, p_reviewer_name text, p_rating integer, p_message text
)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER AS $$
BEGIN
  IF length(trim(p_message)) < 5 THEN RETURN false; END IF;
  INSERT INTO public.teacher_reviews (teacher_id, reviewer_name, rating, message)
  VALUES (p_teacher_id, p_reviewer_name, LEAST(GREATEST(p_rating, 1), 5), p_message);
  RETURN true;
END; $$;

