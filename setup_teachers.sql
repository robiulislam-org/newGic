-- 1. GET ALL ACTIVE TEACHERS (PUBLIC)
CREATE OR REPLACE FUNCTION get_teachers_public()
RETURNS json LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE result json;
BEGIN
  SELECT json_agg(t ORDER BY t.sort_order ASC, t.created_at ASC)
  INTO result FROM public.teachers t WHERE t.is_active = true;
  RETURN COALESCE(result, '[]'::json);
END; $$;

-- 2. GET SINGLE TEACHER BY SLUG (PUBLIC)
CREATE OR REPLACE FUNCTION get_teacher_by_slug(p_slug text)
RETURNS json LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  teacher_row  json;
  reviews_json json;
  result       json;
BEGIN
  SELECT row_to_json(t) INTO teacher_row
  FROM public.teachers t WHERE t.slug = p_slug AND t.is_active = true;
  IF teacher_row IS NULL THEN RETURN NULL; END IF;
  SELECT json_agg(r ORDER BY r.created_at DESC) INTO reviews_json
  FROM public.teacher_reviews r
  WHERE r.teacher_id = (teacher_row->>'id')::bigint AND r.is_approved = true;
  SELECT json_build_object('teacher', teacher_row, 'reviews', COALESCE(reviews_json, '[]'::json)) INTO result;
  RETURN result;
END; $$;

-- 3. ADD TEACHER (ADMIN)
CREATE OR REPLACE FUNCTION add_teacher(
  pass_code text, p_name text, p_slug text,
  p_photo_url text DEFAULT '', p_designation text DEFAULT '',
  p_qualifications text[] DEFAULT '{}', p_bio text DEFAULT '',
  p_experience integer DEFAULT 0, p_students integer DEFAULT 0,
  p_specializations text[] DEFAULT '{}',
  p_schedule jsonb DEFAULT '{"sat":[],"sun":[],"mon":[],"tue":[],"wed":[]}',
  p_whatsapp text DEFAULT '8801733017521', p_sort_order integer DEFAULT 0
)
RETURNS json LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE auth_ok boolean; new_id bigint;
BEGIN
  SELECT (get_admin_auth(pass_code)) INTO auth_ok;
  IF NOT auth_ok THEN RETURN json_build_object('success', false, 'message', 'Unauthorized'); END IF;
  INSERT INTO public.teachers (name, slug, photo_url, designation, qualifications, bio,
    experience_years, students_taught, specializations, weekly_schedule, whatsapp, sort_order)
  VALUES (p_name, p_slug, p_photo_url, p_designation, p_qualifications, p_bio,
    p_experience, p_students, p_specializations, p_schedule, p_whatsapp, p_sort_order)
  RETURNING id INTO new_id;
  RETURN json_build_object('success', true, 'id', new_id, 'message', 'শিক্ষক যোগ করা হয়েছে');
END; $$;

-- 4. UPDATE TEACHER (ADMIN)
CREATE OR REPLACE FUNCTION update_teacher(
  pass_code text, p_id bigint, p_name text, p_slug text,
  p_photo_url text DEFAULT '', p_designation text DEFAULT '',
  p_qualifications text[] DEFAULT '{}', p_bio text DEFAULT '',
  p_experience integer DEFAULT 0, p_students integer DEFAULT 0,
  p_specializations text[] DEFAULT '{}',
  p_schedule jsonb DEFAULT '{"sat":[],"sun":[],"mon":[],"tue":[],"wed":[]}',
  p_whatsapp text DEFAULT '8801733017521', p_sort_order integer DEFAULT 0,
  p_is_active boolean DEFAULT true
)
RETURNS json LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE auth_ok boolean;
BEGIN
  SELECT (get_admin_auth(pass_code)) INTO auth_ok;
  IF NOT auth_ok THEN RETURN json_build_object('success', false, 'message', 'Unauthorized'); END IF;
  UPDATE public.teachers SET
    name = p_name, slug = p_slug, photo_url = p_photo_url, designation = p_designation,
    qualifications = p_qualifications, bio = p_bio, experience_years = p_experience,
    students_taught = p_students, specializations = p_specializations,
    weekly_schedule = p_schedule, whatsapp = p_whatsapp,
    sort_order = p_sort_order, is_active = p_is_active
  WHERE id = p_id;
  RETURN json_build_object('success', true, 'message', 'শিক্ষকের তথ্য আপডেট হয়েছে');
END; $$;

-- 5. DELETE TEACHER (ADMIN)
CREATE OR REPLACE FUNCTION delete_teacher(pass_code text, p_id bigint)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE auth_ok boolean;
BEGIN
