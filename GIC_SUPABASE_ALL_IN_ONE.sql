-- ক. আবেদন জমা দেওয়া (পাবলিক - শিক্ষক হিসেবে যুক্ত হওয়ার ফর্ম থেকে)
CREATE OR REPLACE FUNCTION submit_teacher_application(
  p_category          text DEFAULT 'hafez',
  p_name              text DEFAULT '',
  p_designation       text DEFAULT '',
  p_photo_url         text DEFAULT '',
  p_qualifications    text[] DEFAULT '{}',
  p_specializations   text[] DEFAULT '{}',
  p_experience_years  integer DEFAULT 0,
  p_students_taught   integer DEFAULT 0,
  p_bio               text DEFAULT '',
  p_weekly_schedule   jsonb DEFAULT '{"sat":[],"sun":[],"mon":[],"tue":[],"wed":[]}',
  p_phone             text DEFAULT '',
  p_whatsapp_number   text DEFAULT '',
  p_email             text DEFAULT '',
  p_address           text DEFAULT '',
  p_nid_number        text DEFAULT '',
  p_private_notes     text DEFAULT '',
  p_languages         text[] DEFAULT '{}',
  p_country           text DEFAULT 'বাংলাদেশ',
  p_native_language   text DEFAULT 'বাংলা',
  p_present_address   text DEFAULT '',
  p_permanent_address text DEFAULT '',
  p_nid_front_url     text DEFAULT '',
  p_nid_back_url      text DEFAULT '',
  p_passport_url      text DEFAULT '',
  p_terms_agreed      boolean DEFAULT true,
  p_gender            text DEFAULT 'male',
  p_monthly_fee       text DEFAULT 'আলোচনা সাপেক্ষে',
  p_demo_video_url    text DEFAULT '',
  p_teaching_track    text DEFAULT 'quran',
  p_track             text DEFAULT 'quran',
  p_teaching_mode     text DEFAULT 'online',
  p_offline_areas     text DEFAULT '',
  p_teacher_type      text DEFAULT 'senior'
)
RETURNS json LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE new_id bigint;
BEGIN
  IF trim(p_name) = '' THEN 
    RETURN json_build_object('success', false, 'message', 'নাম পূরণ করা আবশ্যক'); 
  END IF;
  
  INSERT INTO public.teacher_applications (
    category, name, designation, photo_url, qualifications, specializations,
    languages, experience_years, students_taught, bio, weekly_schedule,
    phone, whatsapp_number, email, address, nid_number, private_notes,
    country, native_language, present_address, permanent_address,
    nid_front_url, nid_back_url, passport_url, terms_agreed,
    gender, monthly_fee, demo_video_url, teaching_track, track,
    teaching_mode, offline_areas, teacher_type
  ) VALUES (
    COALESCE(p_category, 'hafez'), trim(p_name), trim(p_designation), trim(p_photo_url),
    p_qualifications, p_specializations, COALESCE(p_languages, '{"বাংলা"}'),
    COALESCE(p_experience_years, 0), COALESCE(p_students_taught, 0),
    trim(p_bio), COALESCE(p_weekly_schedule, '{"sat":[],"sun":[],"mon":[],"tue":[],"wed":[]}'),
    trim(p_phone), trim(p_whatsapp_number),
    trim(p_email), trim(p_address), trim(p_nid_number), trim(p_private_notes),
    COALESCE(trim(p_country), 'বাংলাদেশ'), COALESCE(trim(p_native_language), 'বাংলা'),
    trim(p_present_address), trim(p_permanent_address),
    trim(p_nid_front_url), trim(p_nid_back_url), trim(p_passport_url),
    COALESCE(p_terms_agreed, true),
    COALESCE(p_gender, 'male'), COALESCE(p_monthly_fee, 'আলোচনা সাপেক্ষে'),
    trim(p_demo_video_url),
    COALESCE(p_teaching_track, p_track, 'quran'),
    COALESCE(p_track, p_teaching_track, 'quran'),
    COALESCE(p_teaching_mode, 'online'),
    trim(p_offline_areas),
    COALESCE(p_teacher_type, 'senior')
  ) RETURNING id INTO new_id;

  RETURN json_build_object('success', true, 'id', new_id, 'message', 'আবেদন সফলভাবে জমা হয়েছে');
END; $$;

-- খ. আবেদন অনুমোদন (Approve Teacher Application -> Creates Live Profile with all fields)
CREATE OR REPLACE FUNCTION approve_teacher_application(
  pass_code text, p_app_id bigint, p_slug text,
  p_whatsapp text DEFAULT '8801733017521', p_sort_order integer DEFAULT 0,
  p_teacher_type text DEFAULT 'senior'
)
RETURNS json LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  auth_ok boolean;
  app_row public.teacher_applications%ROWTYPE;
  new_teacher_id bigint;
BEGIN
  SELECT (get_admin_auth(pass_code)) INTO auth_ok;
  IF NOT auth_ok THEN RETURN json_build_object('success', false, 'message', 'অননুমোদিত অ্যাক্সেস'); END IF;
  
  SELECT * INTO app_row FROM public.teacher_applications WHERE id = p_app_id;
  IF NOT FOUND THEN RETURN json_build_object('success', false, 'message', 'আবেদন পাওয়া যায়নি'); END IF;
  
  IF EXISTS (SELECT 1 FROM public.teachers WHERE slug = p_slug) THEN
    RETURN json_build_object('success', false, 'message', 'এই slug ইতোমধ্যে ব্যবহৃত। ভিন্ন slug দিন।');
  END IF;

  INSERT INTO public.teachers (
    name, slug, designation, gender, monthly_fee, hourly_rate, demo_video_url,
    photo_url, qualifications, specializations, languages, experience_years,
    students_taught, bio, weekly_schedule, whatsapp, country, native_language,
    sort_order, is_active, is_verified, rating, teacher_type, is_demo,
    track, teaching_track, teaching_mode, offline_areas
  )
  VALUES (
    app_row.name, p_slug, COALESCE(NULLIF(app_row.designation, ''), 'শিক্ষক'),
    COALESCE(app_row.gender, 'male'), COALESCE(app_row.monthly_fee, 'আলোচনা সাপেক্ষে'),
    COALESCE(app_row.hourly_rate, ''), COALESCE(app_row.demo_video_url, ''),
    COALESCE(app_row.photo_url, ''), COALESCE(app_row.qualifications, '{}'),
    COALESCE(app_row.specializations, '{}'), COALESCE(app_row.languages, '{"বাংলা"}'),
    COALESCE(app_row.experience_years, 0), COALESCE(app_row.students_taught, 0),
    COALESCE(app_row.bio, ''), COALESCE(app_row.weekly_schedule, '{"sat":[],"sun":[],"mon":[],"tue":[],"wed":[]}'::jsonb),
    COALESCE(NULLIF(app_row.whatsapp_number, ''), NULLIF(p_whatsapp, ''), '8801733017521'),
    COALESCE(app_row.country, 'বাংলাদেশ'), COALESCE(app_row.native_language, 'বাংলা'),
    p_sort_order, true, true, 5.0, COALESCE(p_teacher_type, app_row.teacher_type, 'senior'), false,
    COALESCE(app_row.track, app_row.teaching_track, 'quran'),
    COALESCE(app_row.teaching_track, app_row.track, 'quran'),
    COALESCE(app_row.teaching_mode, 'both'),
    COALESCE(app_row.offline_areas, '')
  )
  RETURNING id INTO new_teacher_id;

  UPDATE public.teacher_applications
  SET status = 'approved', reviewed_at = now(), approved_teacher_id = new_teacher_id
  WHERE id = p_app_id;

  RETURN json_build_object('success', true, 'message', 'শিক্ষক সফলভাবে অনুমোদিত এবং প্ল্যাটফর্মে যুক্ত হয়েছে', 'teacher_id', new_teacher_id, 'slug', p_slug);
END; $$;

